def local_midnight_ts(days_ago: int) -> float:
    """Epoch timestamp of local midnight, `days_ago` days before today."""
    d = datetime.now().date() - timedelta(days=days_ago)
    return datetime(d.year, d.month, d.day).timestamp()


def parse_ts(value, default: float) -> float:
    """Parse a record timestamp (epoch number or ISO-8601 string) to epoch."""
    if value is None:
        return default
    if isinstance(value, (int, float)):
        return float(value)
    s = str(value).strip()
    if not s:
        return default
    if s.endswith(("Z", "z")):
        s = s[:-1] + "+00:00"
    try:
        dt = datetime.fromisoformat(s)
    except ValueError:
        return default
    return dt.timestamp()  # naive -> local; aware -> absolute


def _to_int(v):
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


# --------------------------------------------------------------------------- #
# Pricing (model -> USD per 1M tokens)
# --------------------------------------------------------------------------- #

def load_pricing():
    """Load pricing.json (generated by fetch_pricing.py from aihubmix.com)."""
    try:
        with open(BASE_DIR / "pricing.json", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError):
        return {}


PRICING = load_pricing()

# Fallback aliases for model names that don't match aihubmix ids exactly.
MODEL_ALIASES = {
    "deepseek-flash": "deepseek-v4.1-flash",
}


def model_price(model):
    """Return {input, output, cache_read, cache_write} or None for a model name.

    Tries the raw name, then progressively strips a provider prefix (segment
    before the first '/'), then the deepest segment, applying aliases along the
    way. Unmatched models have no price (cost counted as 0).
    """
    if not model:
        return None
    cands = [model]
    if "/" in model:
        cands.append(model.split("/", 1)[1])
        cands.append(model.rsplit("/", 1)[1])
    for c in cands:
        key = MODEL_ALIASES.get(c, c)
        if key in PRICING:
            return PRICING[key]
    return None


def record_cost(model, prompt, completion, cache_read, cache_write):
    """USD cost for a set of token counts; 0.0 when the model is unpriced."""
    p = model_price(model)
    if not p:
        return 0.0
    return (
        prompt * p["input"]
        + completion * p["output"]
        + cache_read * p["cache_read"]
        + cache_write * p["cache_write"]
    ) / 1_000_000.0


