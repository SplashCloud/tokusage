class Store:
    def __init__(self, path):
        self.conn = sqlite3.connect(str(path), check_same_thread=False)
        self.conn.row_factory = sqlite3.Row
        self.lock = threading.Lock()
        self.host_status = {}
        self.active_sessions = {}
        self.conn.execute("PRAGMA journal_mode=WAL")
        with self.conn:
            self.conn.execute(
                """
                CREATE TABLE IF NOT EXISTS usage (
                    key              TEXT PRIMARY KEY,
                    host             TEXT NOT NULL,
                    ts               REAL NOT NULL,
                    model            TEXT NOT NULL,
                    prompt_tokens    INTEGER NOT NULL,
                    completion_tokens INTEGER NOT NULL,
                    cache_read_tokens  INTEGER NOT NULL DEFAULT 0,
                    cache_write_tokens INTEGER NOT NULL DEFAULT 0,
                    total_tokens     INTEGER NOT NULL
                )
                """
            )
            self.conn.execute("CREATE INDEX IF NOT EXISTS idx_usage_ts ON usage(ts)")
            self.conn.execute("CREATE INDEX IF NOT EXISTS idx_usage_model ON usage(model)")

    def insert(self, host, rec) -> bool:
        """Insert one normalized record; returns True if newly inserted."""
        with self.lock:
            with self.conn:  # commit the implicit DML transaction
                cur = self.conn.execute(
                    "INSERT OR IGNORE INTO usage VALUES (?,?,?,?,?,?,?,?,?)",
                    (
                        rec["_key"], host, rec["ts"], rec["model"],
                        rec["prompt_tokens"], rec["completion_tokens"],
                        rec["cache_read_tokens"], rec["cache_write_tokens"],
                        rec["total_tokens"],
                    ),
                )
            return cur.rowcount > 0

    def set_host_status(self, name, status, message="", records=0):
        with self.lock:
            self.host_status[name] = {
                "status": status,
                "message": message,
                "records": records,
                "last_checked": time.time(),
            }

    def set_active_sessions(self, host, sessions, error, ended_keep=600):
        now = time.time()
        with self.lock:
            prev = self.active_sessions.get(host, {})
            prev_active = prev.get("sessions", [])
            prev_ended = prev.get("ended", [])
            if error:
                # keep last known state on a failed poll (don't mark everything ended)
                self.active_sessions[host] = {
                    "sessions": prev_active,
                    "ended": prev_ended,
                    "error": error,
                    "updated_at": now,
                }
                return
            new_ids = {s.get("session_id") for s in sessions}
            ended = [e for e in prev_ended if e.get("session_id") not in new_ids]
            for s in prev_active:
                if s.get("session_id") not in new_ids:
                    ended.append(dict(s, ended_at=now))
            ended = [e for e in ended if now - (e.get("ended_at") or now) <= ended_keep]
            self.active_sessions[host] = {
                "sessions": sessions,
                "ended": ended,
                "error": None,
                "updated_at": now,
            }

    def get_active_sessions(self):
        with self.lock:
            return dict(self.active_sessions)

    def dashboard(self, days, host=None):
        """Return (totals, by_model, by_date, by_host).

        `totals`/`by_model`/`by_date` are scoped to `days` (None=all) and
        optionally to a single `host`; `by_host` is always over all hosts
        (scoped to `days`) so the host list stays populated.
        """
        cols = ("host, ts, model, prompt_tokens, completion_tokens, "
                "cache_read_tokens, cache_write_tokens, total_tokens")
        with self.lock:
            # Per-host totals, unfiltered by host.
            if days:
                host_rows = self.conn.execute(
                    f"SELECT {cols} FROM usage WHERE ts >= ?",
                    (local_midnight_ts(days - 1),),
                ).fetchall()
            else:
                host_rows = self.conn.execute(
                    f"SELECT {cols} FROM usage"
                ).fetchall()

            # Filtered aggregation.
            where, params = [], []
            if days:
                where.append("ts >= ?")
                params.append(local_midnight_ts(days - 1))
            if host:
                where.append("host = ?")
                params.append(host)
            w = ("WHERE " + " AND ".join(where)) if where else ""
            rows = self.conn.execute(
                f"SELECT {cols} FROM usage {w}", params
            ).fetchall()

        def new_bucket():
            return {"prompt_tokens": 0, "completion_tokens": 0,
                    "cache_read_tokens": 0, "cache_write_tokens": 0,
                    "total_tokens": 0, "requests": 0, "cost": 0.0}

        def add(bucket, model, pt, ct, cr, cw, tt):
            bucket["prompt_tokens"] += pt
            bucket["completion_tokens"] += ct
            bucket["cache_read_tokens"] += cr
            bucket["cache_write_tokens"] += cw
            bucket["total_tokens"] += tt
            bucket["requests"] += 1
            bucket["cost"] += record_cost(model, pt, ct, cr, cw)

        totals = new_bucket()
        by_model = {}
        by_date = {}
        by_host = {}

        for host_name, _, model, pt, ct, cr, cw, tt in host_rows:
            bh = by_host.setdefault(host_name, new_bucket())
            bh["total_tokens"] += tt
            bh["requests"] += 1
            bh["cost"] += record_cost(model, pt, ct, cr, cw)

        for _, ts, model, pt, ct, cr, cw, tt in rows:
            add(totals, model, pt, ct, cr, cw, tt)
            m = by_model.setdefault(model, new_bucket())
            add(m, model, pt, ct, cr, cw, tt)
            d = datetime.fromtimestamp(ts).strftime("%Y-%m-%d")
            bd = by_date.setdefault(d, new_bucket())
            add(bd, model, pt, ct, cr, cw, tt)

        return totals, by_model, by_date, by_host

    def heatmap(self, days=30, host=None):
        """Daily total_tokens + requests + cost for the last `days` calendar days (zero-filled)."""
        start = local_midnight_ts(days - 1)
        where, params = "WHERE ts >= ?", [start]
        if host:
            where += " AND host = ?"
            params.append(host)
        with self.lock:
            rows = self.conn.execute(
                f"SELECT ts, model, prompt_tokens, completion_tokens, "
                f"cache_read_tokens, cache_write_tokens, total_tokens FROM usage {where}", params
            ).fetchall()
        daymap = {}
        reqmap = {}
        costmap = {}
        for ts, model, pt, ct, cr, cw, tt in rows:
            d = datetime.fromtimestamp(ts).strftime("%Y-%m-%d")
            daymap[d] = daymap.get(d, 0) + tt
            reqmap[d] = reqmap.get(d, 0) + 1
            costmap[d] = costmap.get(d, 0.0) + record_cost(model, pt, ct, cr, cw)
        today = datetime.now().date()
        out = []
        for i in range(days):
            d = today - timedelta(days=days - 1 - i)
            key = d.isoformat()
            out.append({"date": key, "total_tokens": daymap.get(key, 0),
                        "requests": reqmap.get(key, 0), "cost": costmap.get(key, 0.0)})
        return out

    def heatmap_range(self, end_year, end_month, months, host=None):
        """Daily total_tokens + requests for `months` months ending at end_year/end_month."""
        end = datetime(end_year, end_month, 1)
        nxt = datetime(end_year + 1, 1, 1) if end_month == 12 else datetime(end_year, end_month + 1, 1)
        total_m = end.year * 12 + (end.month - 1)
        start_m = total_m - (months - 1)
        first = datetime(start_m // 12, start_m % 12 + 1, 1)
        start_ts, end_ts = first.timestamp(), nxt.timestamp()
        where, params = "WHERE ts >= ? AND ts < ?", [start_ts, end_ts]
        if host:
            where += " AND host = ?"
            params.append(host)
        with self.lock:
            rows = self.conn.execute(
                f"SELECT ts, model, prompt_tokens, completion_tokens, "
                f"cache_read_tokens, cache_write_tokens, total_tokens FROM usage {where}", params
            ).fetchall()
        daymap, reqmap, costmap = {}, {}, {}
        for ts, model, pt, ct, cr, cw, tt in rows:
            d = datetime.fromtimestamp(ts).strftime("%Y-%m-%d")
            daymap[d] = daymap.get(d, 0) + tt
            reqmap[d] = reqmap.get(d, 0) + 1
            costmap[d] = costmap.get(d, 0.0) + record_cost(model, pt, ct, cr, cw)
        ndays = (nxt - first).days
        return [
            {"date": (first + timedelta(days=i)).strftime("%Y-%m-%d"),
             "total_tokens": daymap.get((first + timedelta(days=i)).strftime("%Y-%m-%d"), 0),
             "requests": reqmap.get((first + timedelta(days=i)).strftime("%Y-%m-%d"), 0),
             "cost": costmap.get((first + timedelta(days=i)).strftime("%Y-%m-%d"), 0.0)}
            for i in range(ndays)
        ]

    def day_breakdown(self, date_str, host=None):
        """totals + by_model for a single calendar day (YYYY-MM-DD)."""
        d = datetime.strptime(date_str, "%Y-%m-%d")
        start_ts, end_ts = d.timestamp(), (d + timedelta(days=1)).timestamp()
        where, params = "WHERE ts >= ? AND ts < ?", [start_ts, end_ts]
        if host:
            where += " AND host = ?"
            params.append(host)
        with self.lock:
            rows = self.conn.execute(
                f"SELECT model, prompt_tokens, completion_tokens, "
                f"cache_read_tokens, cache_write_tokens, total_tokens FROM usage {where}",
                params,
            ).fetchall()
        totals = {"prompt_tokens": 0, "completion_tokens": 0,
                  "cache_read_tokens": 0, "cache_write_tokens": 0,
                  "total_tokens": 0, "requests": 0, "cost": 0.0}
        by_model = {}
        for model, pt, ct, cr, cw, tt in rows:
            totals["prompt_tokens"] += pt
            totals["completion_tokens"] += ct
            totals["cache_read_tokens"] += cr
            totals["cache_write_tokens"] += cw
            totals["total_tokens"] += tt
            totals["requests"] += 1
            totals["cost"] += record_cost(model, pt, ct, cr, cw)
            m = by_model.setdefault(model, {"prompt_tokens": 0, "completion_tokens": 0,
                                            "cache_read_tokens": 0, "cache_write_tokens": 0,
                                            "total_tokens": 0, "requests": 0, "cost": 0.0})
            m["prompt_tokens"] += pt
            m["completion_tokens"] += ct
            m["cache_read_tokens"] += cr
            m["cache_write_tokens"] += cw
            m["total_tokens"] += tt
            m["requests"] += 1
            m["cost"] += record_cost(model, pt, ct, cr, cw)
        return totals, by_model


